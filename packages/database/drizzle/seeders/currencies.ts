import { inArray } from "drizzle-orm";

import type { NodePgDatabase } from "drizzle-orm/node-postgres";
import { currency } from "../schema/base";

export const name = "currencies";

export async function seed(db: NodePgDatabase<Record<string, never>>) {
	const allCodes = currencies.map((c) => c.code);

	const rows = await db
		.select({ code: currency.code })
		.from(currency)
		.where(inArray(currency.code, allCodes));

	const existingSet = new Set(rows.map((r) => r.code));

	const toInsert = currencies.filter((c) => !existingSet.has(c.code));

	if (toInsert.length > 0) {
		await db.insert(currency).values(toInsert);
	}

	console.log(
		`  [currencies] ${toInsert.length} created, ${currencies.length - toInsert.length} skipped (already exist)`,
	);
}

