import { inArray } from "drizzle-orm";

import type { NodePgDatabase } from "drizzle-orm/node-postgres";
import { language } from "../schema/base";

export const name = "languages";

export async function seed(db: NodePgDatabase<Record<string, never>>) {
	const allCodes = languages.map((l) => l.code);

	const rows = await db
		.select({ code: language.code })
		.from(language)
		.where(inArray(language.code, allCodes));

	const existingSet = new Set(rows.map((r) => r.code));

	const toInsert = languages.filter((l) => !existingSet.has(l.code));

	if (toInsert.length > 0) {
		await db.insert(language).values(toInsert);
	}

	console.log(
		`  [languages] ${toInsert.length} created, ${languages.length - toInsert.length} skipped (already exist)`,
	);
}

