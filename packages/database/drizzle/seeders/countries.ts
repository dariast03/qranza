import { inArray } from "drizzle-orm";

import type { NodePgDatabase } from "drizzle-orm/node-postgres";
import { country } from "../schema/base";

export const name = "countries";

export async function seed(db: NodePgDatabase<Record<string, never>>) {
	const allCodes = countries.map((c) => c.code);

	const rows = await db
		.select({ code: country.code })
		.from(country)
		.where(inArray(country.code, allCodes));

	const existingSet = new Set(rows.map((r) => r.code));

	const toInsert = countries.filter((c) => !existingSet.has(c.code));

	if (toInsert.length > 0) {
		await db.insert(country).values(toInsert);
	}

	console.log(
		`  [countries] ${toInsert.length} created, ${countries.length - toInsert.length} skipped (already exist)`,
	);
}

